export const TRY_QUALITYS_LIST = ['master', 'atmos_plus', 'atmos', 'hires', 'flac24bit', 'flac', '320k'] as const
type TryQualityType = typeof TRY_QUALITYS_LIST[number]

/** 歌曲自身元信息里支持的最高档位（不看音源声明） */
export const getSongQuality = (musicInfo: LX.Music.MusicInfoOnline): LX.Quality => {
  const qualitys = musicInfo.meta?._qualitys ?? {}
  return TRY_QUALITYS_LIST.find(q => qualitys[q]) ?? '128k'
}

export const getPlayQuality = (highQuality: LX.Quality, musicInfo: LX.Music.MusicInfoOnline): LX.Quality => {
  // 旧版本存过 192k，该档已从设置里移除，就近映射到 320k（1.22.16）
  if (highQuality == '192k') highQuality = '320k'
  if (!TRY_QUALITYS_LIST.includes(highQuality as TryQualityType)) return '128k'
  const list = global.lx.qualityList[musicInfo.source]

  // 1. 音源声明支持用户档位 → 直接按它请求。
  if (list?.includes(highQuality)) return highQuality

  // 2. 声明里没有用户档位：照样按用户档位请求（1.22.16）。
  //    自定义音源的声明普遍落后于实际能力——kw 未声明 master，
  //    但音源测试页实测 [OK] Master、服务端也能真实返回母带。
  //    之前在这里按声明降级（master→hires/flac24bit），导致「设置选了母带却播 24bit」。
  //    请求失败由上层回退链兜底（见 getQualityFallbacks），不会卡播放。
  if (list) return highQuality

  // 3. 音源信息还没初始化时，退回歌曲自身支持的档位
  const qualitys = musicInfo.meta?._qualitys ?? {}
  const startIndex = TRY_QUALITYS_LIST.indexOf(highQuality as TryQualityType)
  return TRY_QUALITYS_LIST.slice(startIndex).find(q => qualitys[q]) ?? '128k'
}

/**
 * 高档位请求失败后的回退链（1.22.16）。
 * 顺序：音源声明里低于请求档位的最高一档 → 歌曲自身元信息的最高档 → 128k 保底。
 * 最多 3 次请求，失败都是快速报错，不会长时间卡播放。
 */
export const getQualityFallbacks = (targetQuality: LX.Quality, musicInfo: LX.Music.MusicInfoOnline): LX.Quality[] => {
  const startIndex = TRY_QUALITYS_LIST.indexOf(targetQuality as TryQualityType)
  if (startIndex < 0) return ['128k']
  const lower = TRY_QUALITYS_LIST.slice(startIndex + 1)
  const list = global.lx.qualityList[musicInfo.source]
  const qualitys = musicInfo.meta?._qualitys ?? {}
  const chain: LX.Quality[] = []
  const declared = lower.find(q => list?.includes(q))
  if (declared) chain.push(declared)
  const songBest = lower.find(q => qualitys[q])
  if (songBest && !chain.includes(songBest)) chain.push(songBest)
  if (!chain.includes('128k')) chain.push('128k')
  return chain
}

export const getOnlineOtherSourceMusicUrl = async({ musicInfos, quality, onToggleSource, isRefresh, retryedSource = [] }: {
  musicInfos: LX.Music.MusicInfoOnline[]
  quality?: LX.Quality
  onToggleSource: (musicInfo?: LX.Music.MusicInfoOnline) => void
  isRefresh: boolean
  retryedSource?: LX.OnlineSource[]
}): Promise<{
  url: string
  musicInfo: LX.Music.MusicInfoOnline
  quality: LX.Quality
  isFromCache: boolean
}> => {
  if (!await global.lx.apiInitPromise[0]) throw new Error('source init failed')

  let musicInfo: LX.Music.MusicInfoOnline | null = null
  let itemQuality: LX.Quality | null = null
  // eslint-disable-next-line no-cond-assign
  while (musicInfo = (musicInfos.shift()!)) {
    if (retryedSource.includes(musicInfo.source)) continue
    retryedSource.push(musicInfo.source)
    if (!assertApiSupport(musicInfo.source)) continue
    itemQuality = quality ?? getPlayQuality(settingState.setting['player.playQuality'], musicInfo)
    if (!musicInfo.meta._qualitys[itemQuality]) continue

    console.log('try toggle to: ', musicInfo.source, musicInfo.name, musicInfo.singer, musicInfo.interval)
    onToggleSource(musicInfo)
    break
  }
  if (!musicInfo || !itemQuality) throw new Error(global.i18n.t('toggle_source_failed'))

  const cachedUrl = await getStoreMusicUrl(musicInfo, itemQuality)
  if (cachedUrl && !isRefresh) return { url: cachedUrl, musicInfo, quality: itemQuality, isFromCache: true }

  let reqPromise
  try {
    reqPromise = musicSdk[musicInfo.source].getMusicUrl(toOldMusicInfo(musicInfo), itemQuality).promise
  } catch (err: any) {
    reqPromise = Promise.reject(err)
  }
  // retryedSource.includes(musicInfo.source)
  // eslint-disable-next-line @typescript-eslint/promise-function-async
  return reqPromise.then(({ url, type }: { url: string, type: LX.Quality }) => {
    return { musicInfo, url, quality: type, isFromCache: false }
    // eslint-disable-next-line @typescript-eslint/promise-function-async
  }).catch((err: any) => {
    if (err.message == requestMsg.tooManyRequests) throw err
    console.log(err)
    return getOnlineOtherSourceMusicUrl({ musicInfos, quality, onToggleSource, isRefresh, retryedSource })
  })
}

/**
 * 获取在线音乐URL
 */
export const handleGetOnlineMusicUrl = async({ musicInfo, quality, onToggleSource, isRefresh, allowToggleSource }: {
  musicInfo: LX.Music.MusicInfoOnline
  quality?: LX.Quality
  isRefresh: boolean
  allowToggleSource: boolean
  onToggleSource: (musicInfo?: LX.Music.MusicInfoOnline) => void
}): Promise<{
  url: string
  musicInfo: LX.Music.MusicInfoOnline
  quality: LX.Quality
  isFromCache: boolean
}> => {
  dlog('source', 'handleGetOnlineMusicUrl 等待音源初始化', 'source=' + musicInfo.source, 'apiPending=' + !global.lx.apiInitPromise[1])
  const apiReady = await global.lx.apiInitPromise[0]
  dlog('source', '音源初始化结果', 'ready=' + apiReady)
  if (!apiReady) throw new Error('source init failed')
  // console.log(musicInfo.source)
  const targetQuality = quality ?? getPlayQuality(settingState.setting['player.playQuality'], musicInfo)

  let reqPromise
  const reqStart = Date.now()
  dlog('source', '请求播放链接', musicInfo.source, musicInfo.name, targetQuality)
  try {
    reqPromise = musicSdk[musicInfo.source].getMusicUrl(toOldMusicInfo(musicInfo), targetQuality).promise
  } catch (err: any) {
    reqPromise = Promise.reject(err)
  }
  return reqPromise.then(({ url, type }: { url: string, type: LX.Quality }) => {
    dlog('source', '播放链接返回', musicInfo.source, 'quality=' + type, (Date.now() - reqStart) + 'ms')
    return { musicInfo, url, quality: type, isFromCache: false }
  }).catch(async(err: any) => {
    dlog('source', '播放链接失败', musicInfo.source, (Date.now() - reqStart) + 'ms', err?.message ?? err)
    console.log(err)
    if (!allowToggleSource || err.message == requestMsg.tooManyRequests) throw err
    onToggleSource()
    // eslint-disable-next-line @typescript-eslint/promise-function-async
    return getOtherSource(musicInfo).then(otherSource => {
      // console.log('find otherSource', otherSource.length)
      if (otherSource.length) {
        return getOnlineOtherSourceMusicUrl({
          musicInfos: [...otherSource],
          onToggleSource,
          quality,
          isRefresh,
          retryedSource: [musicInfo.source],
        })
      }
      throw err
    })
  })
}


